import { spawnSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// The qwik styled-system needs a Panda CSS release with Qwik v2 support
// (generated createStyleContext + @qwik.dev/core imports). Until that release
// is out, run `bun run codegen` against a linked checkout of the patched
// panda (see PLAN.md Part 1) before typechecking or testing.
const pkgDir = join(dirname(fileURLToPath(import.meta.url)), '..')
const marker = join(pkgDir, 'styled-system/jsx/create-style-context.qwik.mjs')

if (!existsSync(marker)) {
  console.warn(
    '[@park-ui/qwik] styled-system was not generated by a Panda CSS version with Qwik v2 support ' +
      '(missing jsx/create-style-context.qwik.mjs). Skipping. ' +
      'Run codegen with a patched Panda first (see components/qwik/PLAN.md Part 1).',
  )
  process.exit(0)
}

const [cmd, ...args] = process.argv.slice(2)
if (!cmd) process.exit(0)
const result = spawnSync(cmd, args, { stdio: 'inherit', cwd: pkgDir })
process.exit(result.status ?? 1)
